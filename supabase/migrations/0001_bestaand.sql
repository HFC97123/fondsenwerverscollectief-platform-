-- RLS: gepubliceerde inhoud is openbaar, de rest alleen voor beheerders.
create or replace function is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from profiles where id = auth.uid() and role = 'admin');
$$;

do $$
declare t text;
begin
  foreach t in array array['news_articles','blog_posts','videos','resources','sessions','vacancies','course_modules','masterclasses']
  loop
    execute format('alter table %I enable row level security', t);
    execute format('drop policy if exists "gepubliceerd is openbaar" on %I', t);
    execute format($f$
      create policy "gepubliceerd is openbaar" on %I
        for select using (status = 'published' or is_admin())
    $f$, t);
    execute format('drop policy if exists "beheer schrijft" on %I', t);
    execute format($f$
      create policy "beheer schrijft" on %I
        for all using (is_admin()) with check (is_admin())
    $f$, t);
  end loop;
end $$;

alter table profiles enable row level security;
drop policy if exists "eigen profiel lezen" on profiles;
create policy "eigen profiel lezen" on profiles
  for select using (id = auth.uid() or is_admin());
drop policy if exists "eigen profiel wijzigen" on profiles;
create policy "eigen profiel wijzigen" on profiles
  for update using (id = auth.uid() or is_admin());
drop policy if exists "beheer beheert profielen" on profiles;
create policy "beheer beheert profielen" on profiles
  for all using (is_admin()) with check (is_admin());

alter table site_content enable row level security;
drop policy if exists "teksten zijn openbaar" on site_content;
create policy "teksten zijn openbaar" on site_content for select using (true);
drop policy if exists "beheer schrijft teksten" on site_content;
create policy "beheer schrijft teksten" on site_content
  for all using (is_admin()) with check (is_admin());

-- Instellingen bevatten sleutels: alleen beheerders.
alter table site_settings enable row level security;
drop policy if exists "beheer beheert instellingen" on site_settings;
create policy "beheer beheert instellingen" on site_settings
  for all using (is_admin()) with check (is_admin());

alter table applications enable row level security;
drop policy if exists "eigen aanvraag" on applications;
create policy "eigen aanvraag" on applications
  for select using (profile_id = auth.uid() or is_admin());
drop policy if exists "aanvraag indienen" on applications;
create policy "aanvraag indienen" on applications
  for insert with check (profile_id = auth.uid());
drop policy if exists "beheer beheert aanvragen" on applications;
create policy "beheer beheert aanvragen" on applications
  for all using (is_admin()) with check (is_admin());
