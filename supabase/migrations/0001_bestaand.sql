-- Bestaande tabellen: alleen aangemaakt als ze nog niet bestaan.
-- Verandert niets aan kolommen of data van een bestaande tabel.

create extension if not exists "pgcrypto";

-- Leden en hun abonnement.
create table if not exists profiles (
  id uuid primary key references auth.users on delete cascade,
  first_name text,
  last_name text,
  email text,
  member_type text,
  motivation text,
  status text not null default 'pending',       -- pending | approved | rejected
  role text not null default 'member',          -- member | admin
  subscription_tier text not null default 'free', -- free | pro | premium
  subscription_active boolean not null default false,
  trial_started_at timestamptz,
  trial_ends_at timestamptz,
  subscription_started_at timestamptz,
  subscription_ends_at timestamptz,
  stripe_customer_id text,
  stripe_subscription_id text,
  created_at timestamptz not null default now(),
  approved_at timestamptz,
  approved_by uuid references auth.users
);

-- Redactionele inhoud. Alle tabellen delen dezelfde vorm: status + sortering.
create table if not exists news_articles (
  id bigint generated by default as identity primary key,
  status text not null default 'draft',
  tag text, date text, title text, excerpt text, body text, url text,
  sort_order int default 0,
  created_at timestamptz not null default now()
);

create table if not exists blog_posts (
  id bigint generated by default as identity primary key,
  status text not null default 'draft',
  tag text, title text, excerpt text, body text, author text, date text,
  sort_order int default 0,
  created_at timestamptz not null default now()
);

create table if not exists videos (
  id bigint generated by default as identity primary key,
  status text not null default 'draft',
  title text, duration text, level text, url text,
  sort_order int default 0,
  created_at timestamptz not null default now()
);

create table if not exists resources (
  id bigint generated by default as identity primary key,
  status text not null default 'draft',
  type text, format text, title text, url text,
  sort_order int default 0,
  created_at timestamptz not null default now()
);

create table if not exists sessions (
  id bigint generated by default as identity primary key,
  status text not null default 'draft',
  day text, month text, title text, time text, host text, mode text,
  sort_order int default 0,
  created_at timestamptz not null default now()
);

create table if not exists vacancies (
  id bigint generated by default as identity primary key,
  status text not null default 'draft',
  title text, org text, location text, type text, tags text[], url text,
  sort_order int default 0,
  created_at timestamptz not null default now()
);

create table if not exists course_modules (
  id bigint generated by default as identity primary key,
  status text not null default 'draft',
  title text, description text, duration text, level text,
  sort_order int default 0,
  created_at timestamptz not null default now()
);

create table if not exists masterclasses (
  id bigint generated by default as identity primary key,
  status text not null default 'draft',
  title text, description text, date text, host text, location text,
  sort_order int default 0,
  created_at timestamptz not null default now()
);

-- Aanmeldingen die goedkeuring vragen.
create table if not exists applications (
  id bigint generated by default as identity primary key,
  profile_id uuid references profiles on delete cascade,
  first_name text, last_name text, email text, member_type text, motivation text,
  status text not null default 'pending',
  created_at timestamptz not null default now()
);

